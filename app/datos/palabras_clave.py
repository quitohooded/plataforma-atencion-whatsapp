def items_catalogo() -> list[tuple[str, TemaConsulta, float]]:
    """Términos del catálogo como (término, tema, peso)."""
    items = []
    for tema, entradas in CATALOGO.items():
        for entrada in entradas:
            termino, peso = (entrada, 1.0) if isinstance(entrada, str) else entrada
            items.append((termino, tema, float(peso)))
    return items
